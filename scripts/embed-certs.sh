#!/bin/sh
# Generate client/embedded_certs.h from a node's PEM files, so the agent can be
# built as ONE self-contained binary (no ca.crt / node.crt / node.key on the
# device). The Makefile runs this for you via `make EMBED_CERTS=1 ...`; you can
# also run it by hand:
#
#   scripts/embed-certs.sh pki/ca.crt pki/node-mips-0007.crt pki/node-mips-0007.key \
#       > client/embedded_certs.h
#
# The embedded key is the node's identity — the generated header, and any binary
# built from it, is a per-node secret. Don't commit it or share it between nodes.
#
# Portable: needs only POSIX sh, od and awk (present on any build host / BusyBox).
set -eu

# Two modes:
#   CA only (fleet):     scripts/embed-certs.sh <ca.crt>
#     -> embeds just the shared CA; each device still carries its own node.pem.
#   All three (per-node): scripts/embed-certs.sh <ca.crt> <node.crt> <node.key>
#     -> fully standalone, single-node binary (contains that node's private key).
if [ $# -ne 1 ] && [ $# -ne 3 ]; then
  echo "usage: $0 <ca.crt>  |  $0 <ca.crt> <node.crt> <node.key>" >&2
  exit 2
fi

ca=$1
for f in "$@"; do
  [ -r "$f" ] || { echo "cannot read: $f" >&2; exit 1; }
done

emit() {  # <c-array-name> <file>
  name=$1; file=$2
  printf 'static const unsigned char %s[] = {\n' "$name"
  # bytes of the file, then one explicit trailing NUL (mbedTLS PEM parsing
  # requires the length to include the terminating '\0').
  od -An -v -tx1 "$file" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s, ", $i }'
  printf '0x00\n};\n'
  printf 'static const unsigned int %s_len = sizeof(%s);\n\n' "$name" "$name"
}

printf '/* AUTO-GENERATED by scripts/embed-certs.sh — do not edit, do not commit. */\n'
if [ $# -eq 3 ]; then
  printf '/* Contains a node private key: treat this header (and any binary built\n'
  printf '   from it) as a per-node secret. */\n'
fi
printf '#ifndef M12_EMBEDDED_CERTS_H\n#define M12_EMBEDDED_CERTS_H\n\n'
emit embedded_ca "$ca"
if [ $# -eq 3 ]; then
  emit embedded_cert "$2"
  emit embedded_key  "$3"
fi
printf '#endif /* M12_EMBEDDED_CERTS_H */\n'
