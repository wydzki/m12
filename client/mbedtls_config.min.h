/*
 * m12 — minimal mbedTLS 3.6.x build config for the MIPS telemetry agent.
 *
 * This file REPLACES mbedTLS's default config (it is a full MBEDTLS_CONFIG_FILE,
 * not a patch). It enables ONLY what the agent's single use case needs:
 *
 *     TLS 1.2 client, mutual-auth, ECDHE-ECDSA-AES128-GCM-SHA256, curve P-256,
 *     DER certs/key embedded at build time, no clock dependency.
 *
 * Everything else the stock build drags in — TLS 1.3, RSA, DHE, PSK, CBC/CCM/
 * ChaCha20, ARIA/Camellia/3DES, SHA-1/MD5/SHA-512, every curve but P-256, the
 * error-string tables, self-tests — is left out. That is where the ~800 KB
 * comes from; trimmed, the whole static agent is typically ~200 KB or less.
 *
 * Build it via:  make MINIMAL_TLS=1
 * (the Makefile passes -DMBEDTLS_CONFIG_FILE for BOTH the library and the agent,
 *  so their struct layouts match — never define it for only one).
 *
 * If `make` stops with an #error from mbedtls/check_config.h, it means a
 * required dependency is missing — enable exactly what it names and rebuild.
 * (Starting point if you'd rather not hand-trim: the tarball ships
 * configs/config-suite-b.h, which also compiles; this file is more aggressive —
 * P-256 + AES-128 only, no P-384/AES-256.)
 *
 * IMPORTANT: do NOT include check_config.h in this file. In mbedTLS 3.6.x
 * build_info.h includes the config, runs the config_adjust_*.h derivation
 * headers, and then runs check_config.h — in that order. Including it here
 * would check before the derived macros (MBEDTLS_MD_CAN_*) exist.
 *
 * ASSUMPTIONS about your PKI (from scripts/pki.sh): EC P-256 keys, SHA-256
 * signatures, unencrypted private keys. Certs are embedded as DER byte arrays
 * (scripts/embed-certs.sh converts PEM→DER at build time). If your certs are
 * RSA or SHA-1 signed you must re-enable the matching modules below.
 */
#ifndef MBEDTLS_CONFIG_MIN_H
#define MBEDTLS_CONFIG_MIN_H

/* ---- system / platform ---- */
#define MBEDTLS_HAVE_ASM
/* HAVE_TIME / HAVE_TIME_DATE deliberately omitted: many target routers have
 * no RTC and boot with the clock at 1970, which makes mbedTLS reject every
 * certificate as expired.  Without these, validity dates are not checked. */
/* FS_IO omitted: the EMBED_CERTS build uses buffer-based parsing only. */
/* NET_C omitted: client.c uses inline POSIX sockets (~30 lines) instead
 * of the mbedTLS net_sockets module, saving ~2 KB. */

/* ---- RNG / entropy (Linux reads /dev/urandom) ---- */
#define MBEDTLS_ENTROPY_C
#define MBEDTLS_CTR_DRBG_C

/* ---- symmetric: AES-128-GCM only ---- */
#define MBEDTLS_AES_C
#define MBEDTLS_GCM_C
#define MBEDTLS_CIPHER_C

/* ---- hash: SHA-256 only (PRF, HMAC, cert sigs, entropy accumulator) ---- */
#define MBEDTLS_MD_C
#define MBEDTLS_SHA256_C
/* SHA-224 omitted: we only use SHA-256. */

/* ---- public key: EC only, P-256 only ---- */
#define MBEDTLS_BIGNUM_C
#define MBEDTLS_ECP_C
#define MBEDTLS_ECP_DP_SECP256R1_ENABLED
#define MBEDTLS_ECDH_C
#define MBEDTLS_ECDSA_C
#define MBEDTLS_ASN1_PARSE_C
#define MBEDTLS_ASN1_WRITE_C
#define MBEDTLS_OID_C
#define MBEDTLS_PK_C
#define MBEDTLS_PK_PARSE_C
/* BASE64_C and PEM_PARSE_C omitted: the EMBED_CERTS build path uses DER
 * byte arrays (generated by scripts/embed-certs.sh), so no PEM decoding
 * is needed, saving ~3 KB of code + tables. */

/* ---- X.509: parse+verify a server cert chain, present our own ---- */
#define MBEDTLS_X509_USE_C
#define MBEDTLS_X509_CRT_PARSE_C

/* ---- TLS: 1.2 client, one key exchange ---- */
#define MBEDTLS_SSL_TLS_C
#define MBEDTLS_SSL_CLI_C
#define MBEDTLS_SSL_PROTO_TLS1_2
#define MBEDTLS_KEY_EXCHANGE_ECDHE_ECDSA_ENABLED
/* SSL_KEEP_PEER_CERTIFICATE omitted: the agent never inspects the
 * server cert after the handshake, so drop the storage + code. */

/* Keep mbedtls_strerror() linkable without the multi-KB string tables that
 * MBEDTLS_ERROR_C would pull in (the agent calls it in emit_err()). */
#define MBEDTLS_ERROR_STRERROR_DUMMY

/* ---- size tuning ---- */
#define MBEDTLS_SSL_IN_CONTENT_LEN   2048   /* EC cert chain ~1KB; default 16KB */
#define MBEDTLS_SSL_OUT_CONTENT_LEN  2048   /* agent payloads are tiny JSON     */
#define MBEDTLS_AES_ONLY_128_BIT_KEY_LENGTH /* drop AES-192/256 code + tables  */
#define MBEDTLS_AES_FEWER_TABLES            /* smaller AES tables, slightly slower */
#define MBEDTLS_AES_ROM_TABLES              /* const S-boxes in .rodata, no init */
#define MBEDTLS_SHA256_SMALLER              /* smaller SHA-256 core            */
#define MBEDTLS_ECP_NIST_OPTIM              /* compact + fast for NIST curves  */
#define MBEDTLS_ECP_WINDOW_SIZE      2      /* smallest precompute window      */
#define MBEDTLS_ECP_FIXED_POINT_OPTIM 0     /* drop the large fixed-point table */

/* NOTE: do NOT #include "mbedtls/check_config.h" here.
 * In mbedTLS 3.6.x, build_info.h includes this config, then runs the
 * config_adjust_*.h headers that derive computed macros (MBEDTLS_MD_CAN_SHA256,
 * MBEDTLS_PK_HAVE_ECC_KEYS, etc.) from the raw defines above, and THEN
 * includes check_config.h.  Including it prematurely here would run the
 * checks before those derived macros exist, causing false-positive errors. */

#endif /* MBEDTLS_CONFIG_MIN_H */
